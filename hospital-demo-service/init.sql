-- ============================================================
-- MOCK AVAILABILITY
-- 30-minute slots, 9:00 AM to 5:00 PM, for the next 14 days,
-- for every doctor. Roughly 30% of slots are randomly pre-booked
-- so availability looks realistic in the demo.
-- ============================================================

BEGIN
    FOR doc IN (SELECT doctor_id FROM doctors) LOOP
        FOR day_offset IN 0..13 LOOP
            FOR slot_num IN 0..15 LOOP
                INSERT INTO doctor_availability (doctor_id, start_time, end_time, is_booked)
                VALUES (
                    doc.doctor_id,
                    CAST(TRUNC(SYSDATE) + day_offset AS TIMESTAMP) + NUMTODSINTERVAL(9 * 60 + slot_num * 30, 'MINUTE'),
                    CAST(TRUNC(SYSDATE) + day_offset AS TIMESTAMP) + NUMTODSINTERVAL(9 * 60 + slot_num * 30 + 30, 'MINUTE'),
                    CASE WHEN DBMS_RANDOM.VALUE(0, 1) < 0.3 THEN 1 ELSE 0 END
                );
            END LOOP;
        END LOOP;
    END LOOP;
    COMMIT;
END;
