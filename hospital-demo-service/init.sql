-- ============================================================
-- TABLES
-- ============================================================

CREATE TABLE patients (
    patient_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(20) NOT NULL UNIQUE,
    national_id VARCHAR2(20),
    mrn VARCHAR2(20),
    gender VARCHAR2(10),
    dob DATE,
    last_visit DATE,
    medical_history VARCHAR2(500)
);

CREATE TABLE departments (
    department_id NUMBER PRIMARY KEY,
    name VARCHAR2(50) NOT NULL,
    branch VARCHAR2(50) NOT NULL,
    CONSTRAINT uq_department UNIQUE (name, branch)
);

CREATE TABLE doctors (
    doctor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    specialty VARCHAR2(150),
    department_id NUMBER NOT NULL REFERENCES departments(department_id)
);

CREATE TABLE doctor_availability (
    availability_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id NUMBER NOT NULL REFERENCES doctors(doctor_id),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    is_booked NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE TABLE appointments (
    appointment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id NUMBER REFERENCES patients(patient_id),
    doctor_id NUMBER REFERENCES doctors(doctor_id),
    availability_id NUMBER REFERENCES doctor_availability(availability_id),
    appointment_date TIMESTAMP NOT NULL,
    reason VARCHAR2(200),
    status VARCHAR2(20) DEFAULT 'SCHEDULED'
);

CREATE INDEX idx_avail_doctor_time ON doctor_availability (doctor_id, start_time);
CREATE INDEX idx_appt_patient ON appointments (patient_id);

